"""OpenMM helpers for the peptide self-assembly notebook."""

from pathlib import Path
from typing import Union

from openmm import Platform, VerletIntegrator, unit
from openmm.app import ForceField, NoCutoff, PDBFile, Simulation


def minimize_peptides(coord_dir: Union[str, Path]) -> list[Path]:
    """Energy-minimize the 20 VMD-built Tyr-X-Tyr peptide structures.

    Each ``TYR-*-TYR_aa.pdb`` file in ``coord_dir`` is minimized on the
    OpenMM CPU platform with CHARMM36 and OBC2 implicit solvent. The minimized
    coordinates overwrite the input PDB file, matching the notebook workflow.

    Parameters
    ----------
    coord_dir
        Directory containing the PDB files generated by ``make_peptides.sh``.

    Returns
    -------
    list[pathlib.Path]
        The 20 minimized PDB paths, sorted by filename.
    """
    coord_dir = Path(coord_dir)
    generated = sorted(coord_dir.glob("TYR-*-TYR_aa.pdb"))
    assert len(generated) == 20, "Run make_peptides.sh before minimizing."

    forcefield = ForceField("charmm36.xml", "implicit/obc2.xml")
    platform = Platform.getPlatformByName("CPU")

    for pdb_file in generated:
        pdb = PDBFile(str(pdb_file))
        system = forcefield.createSystem(pdb.topology, nonbondedMethod=NoCutoff)
        integrator = VerletIntegrator(0.001 * unit.picoseconds)
        simulation = Simulation(pdb.topology, system, integrator, platform)
        simulation.context.setPositions(pdb.positions)

        before = simulation.context.getState(getEnergy=True).getPotentialEnergy()
        simulation.minimizeEnergy(
            tolerance=10 * unit.kilojoule_per_mole / unit.nanometer,
            maxIterations=500,
        )
        state = simulation.context.getState(getEnergy=True, getPositions=True)
        after = state.getPotentialEnergy()

        with pdb_file.open("w") as output:
            PDBFile.writeFile(
                pdb.topology,
                state.getPositions(),
                output,
                keepIds=True,
            )

        before_kj_mol = before.value_in_unit(unit.kilojoule_per_mole)
        after_kj_mol = after.value_in_unit(unit.kilojoule_per_mole)
        print(f"{pdb_file.name}: {before_kj_mol:.1f} kJ/mol -> "
              f"{after_kj_mol:.1f} kJ/mol")

    return generated
